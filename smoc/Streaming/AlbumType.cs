namespace Smoc.Streaming;

/// <summary>
/// Specifies the type of an album release.
/// </summary>
public enum AlbumType {
  /// <summary>
  /// A standard full-length album (LP).
  /// </summary>
  Album,

  /// <summary>
  /// An extended play release (EP).
  /// </summary>
  Ep,

  /// <summary>
  /// A standalone single release.
  /// </summary>
  Single
}
